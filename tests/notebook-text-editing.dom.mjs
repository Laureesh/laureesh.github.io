import assert from 'node:assert/strict';
import test from 'node:test';
import { createRequire } from 'node:module';
import { checklistRoot } from '../src/pages/admin/notebook/checklistDocument.ts';
import { editableTextBlocks, saveChecklistText, textParts } from '../src/pages/admin/notebook/checklistTextEditing.ts';
const { parseHTML } = createRequire(import.meta.url)(process.env.DOM_TEST_MODULE || 'linkedom');
const { window } = parseHTML('<html><body></body></html>');
for (const name of ['document', 'Node', 'Element']) globalThis[name] = window[name];
const source = '<h1>My plan</h1><p>Tags: Weight Loss</p><p>Plan start: <span data-weightloss-start-label>10/26/2026</span>. <strong>Seven sessions</strong> <a href="https://example.com">More</a></p><ul class="notebook-todo"><li><input type="checkbox" checked data-checklist-date="2026-10-26"><p>Task details</p></li></ul><div data-fitness-values="{}"><p>Calculated values</p></div>';
test('intro edits preserve formatting, dates, links, and checklist state', () => {
  let html = saveChecklistText(source, 0, ['New title']);
  html = saveChecklistText(html, 1, ['Tags: My fitness']);
  const blocks = editableTextBlocks(checklistRoot(html));
  assert.equal(blocks.length, 3);
  const parts = textParts(blocks[2]);
  assert.equal(parts[1].locked, true);
  const values = parts.map(part => part.node.textContent);
  values[0] = 'My start: '; values[1] = '2099-01-01'; values[3] = 'My sessions';
  html = saveChecklistText(html, 2, values);
  const root = checklistRoot(html);
  assert.equal(root.querySelector('h1').textContent, 'New title');
  assert.equal(root.querySelector('[data-weightloss-start-label]').textContent, '10/26/2026');
  assert.equal(root.querySelector('strong').textContent, 'My sessions');
  assert.equal(root.querySelector('a').getAttribute('href'), 'https://example.com');
  assert(root.querySelector('input').hasAttribute('checked'));
  assert.equal(root.querySelector('input').getAttribute('data-checklist-date'), '2026-10-26');
});
test('plain text is escaped, and cleared paragraphs can be edited again', () => {
  const html = saveChecklistText('<p>Hello</p>', 0, ['<script>alert(1)</script>']);
  assert.equal(checklistRoot(html).querySelector('script'), null);
  const empty = saveChecklistText('<p>Hello</p>', 0, ['']);
  assert.equal(checklistRoot(saveChecklistText(empty, 0, ['Restored'])).textContent, 'Restored');
});
